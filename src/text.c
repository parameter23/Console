/** @brief See draw_text() in the header for the full contract. */
void draw_text(int x, int y, const char *s, uint8_t color)
{
    while (*s) {
        uint32_t cp;
        s = decode_utf8(s, &cp);
        uint8_t byte = (cp < 0x80) ? (uint8_t)cp : unicode_to_cp850(cp);
        draw_char(x, y, (char)byte, color);
        x += 8;
    }
}
