/**
 * @file font8x8.c
 * @brief Glyph data for the 8x8 font (see font8x8.h): full Code Page 850.
 *
 * Indices 32-126 (printable ASCII) and 127 are this project's own
 * original glyphs, unchanged from the ASCII-only table this replaces, so
 * every game's existing on-screen text renders identically to before.
 * 0x00-0x1F is the standard CP437 control-range icon set (CP437 and
 * CP850 agree here - only 0x80-0xFF differs between the two codepages),
 * transposed from greiman/SSD1306Ascii's cp437font8x8.h (MIT license)
 * from its native column-major/LSB-top byte layout into this file's
 * row-major/MSB-left one (see draw_char() in text.c for the bit
 * convention). 0x80-0xFF is Code Page 850 (Western European DOS Latin-1
 * - more accented Latin letters than CP437, fewer box-drawing/Greek/math
 * symbols), taken byte-for-byte (already row-major, no transpose needed)
 * from IBM PC-DOS 2000's own ROM font
 * (viler-int10h/vga-text-mode-fonts, FONTS/SYSTEM/PCDOS2K/CP850.F08 -
 * that repo's FONTS.TXT states plain bitmap fonts like this aren't
 * believed to carry restrictive copyright). Cross-checked against that
 * same source's CP437.F08 sibling: byte-identical to it over 0x00-0x7F,
 * confirming both codepages' shared ASCII range - and so, by extension,
 * this table's own CP850 data - are self-consistent.
 *
 * Note PC-DOS 2000's font has a visibly different, more refined letter
 * style than this project's original 32-126 glyphs (compare e.g. 'A' at
 * index 65 to Á at 0xB5) - a style seam exactly at the 0x80 boundary.
 * Left as-is rather than blended/redrawn: swapping the whole table to
 * PC-DOS 2000's style would change the look of every existing game's
 * on-screen text, and hand-tuning ~30 new glyphs to blend both styles
 * risks looking worse than either style consistently. Revisit if this
 * seam bothers the user.
 *
 * A raw byte 0x80-0xFF in a string literal now selects the matching
 * CP850 glyph directly (e.g. "\x80" is C-cedilla, same as CP437) - this
 * is Code Page 850, not UTF-8, so a literal accented character typed
 * directly into a source file (which this project saves as UTF-8) will
 * NOT render correctly; it must be written as an explicit CP850 byte
 * escape.
 */
